-- Tabelas e indices da pesquisa e das contas (gerado do esquema SQLite real por scripts/gerar_esquema_postgres.py).

CREATE TABLE IF NOT EXISTS execucoes (
    run_id        TEXT COLLATE "C" PRIMARY KEY,
    iniciado_em   TEXT COLLATE "C" NOT NULL,
    finalizado_em TEXT COLLATE "C",
    comando       TEXT COLLATE "C",
    config_hash   TEXT COLLATE "C" NOT NULL,
    config_json   TEXT COLLATE "C" NOT NULL,
    commit_git    TEXT COLLATE "C",
    status        TEXT COLLATE "C" NOT NULL DEFAULT 'em_andamento',
    metricas_json TEXT COLLATE "C",
    run_origem    TEXT COLLATE "C",                             -- C5: run (--de) that holds the input of this one
    ambiente_json TEXT COLLATE "C",                             -- versoes, pausas e argumentos da execucao (fora do hash)
    no_relatorio  BIGINT NOT NULL DEFAULT 1,       -- 0 = execucao de teste/piloto: fora das views agregadas do relatorio
    motivo_exclusao TEXT COLLATE "C",
    excluida_em   TEXT COLLATE "C",
    ordem_gravacao BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE  -- desempate pela ordem de gravacao (o rowid do SQLite)
);

CREATE TABLE IF NOT EXISTS execucoes_retomadas (
    retomada_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id        TEXT COLLATE "C" NOT NULL REFERENCES execucoes(run_id),
    retomado_em   TEXT COLLATE "C" NOT NULL,
    commit_git    TEXT COLLATE "C",
    ambiente_json TEXT COLLATE "C"
);

CREATE TABLE IF NOT EXISTS metricas_run (          -- free-form counters per run (no schema change needed)
    run_id TEXT COLLATE "C" NOT NULL REFERENCES execucoes(run_id),
    chave  TEXT COLLATE "C" NOT NULL,
    valor  DOUBLE PRECISION,
    PRIMARY KEY (run_id, chave)
);

CREATE TABLE IF NOT EXISTS saldos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id TEXT COLLATE "C" NOT NULL REFERENCES execucoes(run_id),
    provedor TEXT COLLATE "C" NOT NULL,
    momento TEXT COLLATE "C" NOT NULL,                          -- inicio | fim
    valor DOUBLE PRECISION,
    registrado_em TEXT COLLATE "C"
);

CREATE TABLE IF NOT EXISTS chamadas (
    chamada_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id             TEXT COLLATE "C" NOT NULL REFERENCES execucoes(run_id),
    etapa              TEXT COLLATE "C" NOT NULL,               -- busca_academica | busca_web | download | classificacao
    provedor           TEXT COLLATE "C" NOT NULL,
    operacao           TEXT COLLATE "C",
    alvo_tipo          TEXT COLLATE "C",                        -- termo | consulta_web | url | item
    alvo_id            TEXT COLLATE "C",
    uf                 TEXT COLLATE "C",
    pagina             BIGINT,
    parametros_json    TEXT COLLATE "C" NOT NULL,
    chave_idempotencia TEXT COLLATE "C" NOT NULL,
    requisitado_em     TEXT COLLATE "C" NOT NULL,
    http_status        BIGINT,
    sucesso            BIGINT NOT NULL DEFAULT 0,
    tentativas         BIGINT,
    latencia_ms        BIGINT,
    id_externo         TEXT COLLATE "C",
    total_reportado    BIGINT,
    n_retornados       BIGINT,
    n_novos            BIGINT,
    tokens_entrada     BIGINT,
    tokens_saida       BIGINT,
    custo_usd          DOUBLE PRECISION,
    erro               TEXT COLLATE "C",
    raw_path           TEXT COLLATE "C",
    raw_sha256         TEXT COLLATE "C",
    extras_json        TEXT COLLATE "C"
);

CREATE TABLE IF NOT EXISTS artigos (
    artigo_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chave_dedup        TEXT COLLATE "C" NOT NULL UNIQUE,
    titulo             TEXT COLLATE "C" NOT NULL,
    link               TEXT COLLATE "C",
    autores_publicacao TEXT COLLATE "C",
    ano                BIGINT,
    snippet            TEXT COLLATE "C",
    citacoes           BIGINT,
    primeira_vez_run   TEXT COLLATE "C",
    primeira_vez_em    TEXT COLLATE "C"
);

CREATE TABLE IF NOT EXISTS ocorrencias (
    ocorrencia_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chamada_id          BIGINT NOT NULL REFERENCES chamadas(chamada_id),
    artigo_id           BIGINT NOT NULL REFERENCES artigos(artigo_id),
    termo_id            TEXT COLLATE "C" NOT NULL,
    run_id              TEXT COLLATE "C" NOT NULL,
    posicao             BIGINT,
    citacoes_no_momento BIGINT
);

CREATE TABLE IF NOT EXISTS triagem (
    artigo_id          BIGINT PRIMARY KEY REFERENCES artigos(artigo_id),
    decisao            TEXT COLLATE "C" NOT NULL DEFAULT 'pendente',   -- pendente | incluir | excluir
    motivo             TEXT COLLATE "C",
    confirmado_em_base TEXT COLLATE "C",
    link_confirmado    TEXT COLLATE "C",
    revisor            TEXT COLLATE "C",
    revisado_em        TEXT COLLATE "C",
    decisao_texto_completo TEXT COLLATE "C",                        -- pendente | incluir | excluir (etapa de elegibilidade)
    motivo_texto_completo  TEXT COLLATE "C"
);

CREATE TABLE IF NOT EXISTS triagem_revisoes (
    revisao_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artigo_id  BIGINT NOT NULL REFERENCES artigos(artigo_id),
    revisor    TEXT COLLATE "C" NOT NULL,
    decisao    TEXT COLLATE "C" NOT NULL,
    motivo     TEXT COLLATE "C",
    decisao_texto_completo TEXT COLLATE "C",
    motivo_texto_completo  TEXT COLLATE "C",
    importado_em TEXT COLLATE "C" NOT NULL,
    independente BIGINT NOT NULL DEFAULT 0          -- 1 = revisao independente (so historico); so estas entram no kappa
);

CREATE TABLE IF NOT EXISTS ocorrencias_manuais (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artigo_id   BIGINT NOT NULL REFERENCES artigos(artigo_id),
    base        TEXT COLLATE "C" NOT NULL,
    termo_id    TEXT COLLATE "C" NOT NULL,
    data_busca  TEXT COLLATE "C" NOT NULL DEFAULT '',
    posicao     BIGINT,
    importado_em TEXT COLLATE "C",
    UNIQUE (artigo_id, base, termo_id, data_busca)
);

CREATE TABLE IF NOT EXISTS buscas_manuais (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    base           TEXT COLLATE "C" NOT NULL,
    termo_id       TEXT COLLATE "C" NOT NULL,
    string_base    TEXT COLLATE "C",
    filtros        TEXT COLLATE "C",
    n_resultados   BIGINT,
    n_apos_filtro  BIGINT,
    n_selecionados BIGINT,
    data_busca     TEXT COLLATE "C",
    observacao     TEXT COLLATE "C"
);

CREATE TABLE IF NOT EXISTS urls (                   -- one row per normalized (deduplicated) URL
    url_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url_normalizada  TEXT COLLATE "C" NOT NULL UNIQUE,
    url_original     TEXT COLLATE "C" NOT NULL,
    dominio          TEXT COLLATE "C",
    fonte_oficial    BIGINT,
    primeira_vez_run TEXT COLLATE "C",
    primeira_vez_em  TEXT COLLATE "C"
);

CREATE TABLE IF NOT EXISTS resultados_web (
    resultado_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chamada_id   BIGINT NOT NULL REFERENCES chamadas(chamada_id),
    run_id       TEXT COLLATE "C" NOT NULL,
    consulta_id  TEXT COLLATE "C" NOT NULL,
    uf           TEXT COLLATE "C" NOT NULL,
    tecnologia   TEXT COLLATE "C",
    perfil       TEXT COLLATE "C",
    url_id       BIGINT NOT NULL REFERENCES urls(url_id),
    posicao      BIGINT,
    titulo       TEXT COLLATE "C",
    snippet      TEXT COLLATE "C",
    data_pub     TEXT COLLATE "C",
    cidade       TEXT COLLATE "C"                                 -- NULL = secretaria estadual; preenchido = municipal
);

CREATE TABLE IF NOT EXISTS selecao_download (       -- EVERY decision to download or discard is recorded
    run_id      TEXT COLLATE "C" NOT NULL REFERENCES execucoes(run_id),
    url_id      BIGINT NOT NULL REFERENCES urls(url_id),
    uf          TEXT COLLATE "C" NOT NULL,
    selecionada BIGINT NOT NULL,
    motivo      TEXT COLLATE "C",                                -- dominio_excluido | nao_oficial | prefiltro_palavras | limite_por_uf
    auditoria   BIGINT NOT NULL DEFAULT 0,          -- 1 = descartada pelo pre-filtro, mas baixada e classificada para auditar o filtro
    PRIMARY KEY (run_id, url_id, uf)
);

CREATE TABLE IF NOT EXISTS paginas (
    pagina_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id        TEXT COLLATE "C" NOT NULL,
    url_id        BIGINT NOT NULL REFERENCES urls(url_id),
    chamada_id    BIGINT NOT NULL REFERENCES chamadas(chamada_id),
    url_final     TEXT COLLATE "C",
    http_status   BIGINT,
    content_type  TEXT COLLATE "C",
    n_bytes       BIGINT,
    truncado      BIGINT,
    texto_path    TEXT COLLATE "C",
    n_chars       BIGINT,
    extrator      TEXT COLLATE "C",
    extracao_ok   BIGINT,
    motivo_falha  TEXT COLLATE "C",
    dominio_final TEXT COLLATE "C",                              -- dominio de url_final (apos redirecionamentos)
    fonte_oficial_final BIGINT                      -- 1 se o dominio final e oficial (.gov.br)
);

CREATE TABLE IF NOT EXISTS classificacoes (
    classificacao_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chamada_id          BIGINT NOT NULL REFERENCES chamadas(chamada_id),
    run_id              TEXT COLLATE "C" NOT NULL,
    url_id              BIGINT NOT NULL REFERENCES urls(url_id),
    pagina_id           BIGINT REFERENCES paginas(pagina_id),
    uf                  TEXT COLLATE "C" NOT NULL,
    origem_texto        TEXT COLLATE "C",                        -- pagina | snippet
    texto_truncado      BIGINT,
    n_chars_enviados    BIGINT,
    classificador       TEXT COLLATE "C",
    cidade              TEXT COLLATE "C",                        -- NULL = estadual; preenchido = secretaria municipal
    prompt_versao       TEXT COLLATE "C",
    relevante           BIGINT,
    json_valido         BIGINT,
    n_achados           BIGINT,
    n_achados_invalidos BIGINT,
    resposta_texto      TEXT COLLATE "C"
);

CREATE TABLE IF NOT EXISTS achados (
    achado_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classificacao_id  BIGINT NOT NULL REFERENCES classificacoes(classificacao_id),
    uf                TEXT COLLATE "C" NOT NULL,
    tecnologia        TEXT COLLATE "C",
    status_reportado  TEXT COLLATE "C",
    fornecedor        TEXT COLLATE "C",
    menciona_lgpd     BIGINT,
    evidencia         TEXT COLLATE "C",
    evidencia_confere BIGINT,                       -- 1 = the excerpt exists in the text that was sent
    confianca         TEXT COLLATE "C",
    confianca_original TEXT COLLATE "C",                         -- confianca devolvida pelo modelo, antes do rebaixamento
    evidencia_cita_tecnologia BIGINT,               -- 1 = o trecho cita um termo da tecnologia (heuristica, sem LLM)
    evidencia_cita_lgpd BIGINT,                     -- 1 = o trecho cita LGPD ou protecao de dados (heuristica)
    nome_solucao      TEXT COLLATE "C",                          -- nome proprio da solucao (prompt v4), so se aparece no texto enviado; NULL = sem nome
    verificado        BIGINT NOT NULL DEFAULT 0,
    status_final      TEXT COLLATE "C",                          -- human decision
    verificado_por    TEXT COLLATE "C",
    verificado_em     TEXT COLLATE "C",
    observacao        TEXT COLLATE "C"
);

CREATE TABLE IF NOT EXISTS achados_descartados (
    descartado_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classificacao_id BIGINT NOT NULL REFERENCES classificacoes(classificacao_id),
    uf               TEXT COLLATE "C",
    tecnologia       TEXT COLLATE "C",
    status           TEXT COLLATE "C",
    fornecedor       TEXT COLLATE "C",
    menciona_lgpd    BIGINT,
    evidencia        TEXT COLLATE "C",
    confianca        TEXT COLLATE "C",
    motivo           TEXT COLLATE "C"                     -- tecnologia_fora_do_vocabulario | status_fora_do_vocabulario
);

CREATE TABLE IF NOT EXISTS achados_revisoes (
    revisao_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achado_id      BIGINT NOT NULL REFERENCES achados(achado_id),
    verificado_por TEXT COLLATE "C" NOT NULL,
    status_final   TEXT COLLATE "C",
    observacao     TEXT COLLATE "C",
    importado_em   TEXT COLLATE "C" NOT NULL,
    anterior_json  TEXT COLLATE "C",                  -- estado antes de uma decisao do painel (permite desfazer)
    posterior_json TEXT COLLATE "C",                  -- estado que a decisao produziu: o desfazer so vale se o achado ainda esta assim
    desfeita       BIGINT NOT NULL DEFAULT 0,
    independente   BIGINT NOT NULL DEFAULT 0   -- 1 = revisao independente (achados-importar --independente): so historico; so estas entram no kappa
);

CREATE TABLE IF NOT EXISTS auditoria_negativos (
    auditoria_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classificacao_id BIGINT NOT NULL REFERENCES classificacoes(classificacao_id),
    url_id           BIGINT NOT NULL REFERENCES urls(url_id),
    uf               TEXT COLLATE "C" NOT NULL,
    revisor          TEXT COLLATE "C" NOT NULL,
    revisado_em      TEXT COLLATE "C" NOT NULL,
    tinha_aplicacao  BIGINT NOT NULL CHECK (tinha_aplicacao IN (0, 1)),   -- 1 = o modelo perdeu uma aplicacao; 0 = o modelo acertou
    tecnologia       TEXT COLLATE "C",                                                  -- do vocabulario; so quando tinha_aplicacao = 1
    observacao       TEXT COLLATE "C",
    UNIQUE (classificacao_id, revisor)
);

CREATE TABLE IF NOT EXISTS triagem_escopo (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id             TEXT COLLATE "C" NOT NULL REFERENCES execucoes(run_id),
    chamada_id         BIGINT REFERENCES chamadas(chamada_id),     -- a chamada (lote) que respondeu
    fonte              TEXT COLLATE "C" NOT NULL,                                -- artigo | web
    item_id            BIGINT NOT NULL,
    uf                 TEXT COLLATE "C" NOT NULL DEFAULT '',
    provedor           TEXT COLLATE "C",                                         -- serpapi_scholar, perplexity_search, serpapi_google
    termos_consulta    TEXT COLLATE "C",                                         -- JSON: textos das consultas (termos) que acharam o item
    status             TEXT COLLATE "C" NOT NULL,                                -- elegivel | quarentena | excluido (depois da regra de seguranca)
    status_bruto       TEXT COLLATE "C",                                         -- o que o modelo disse, antes do rebaixamento
    confianca          TEXT COLLATE "C",                                         -- alta | media | baixa
    categoria_motivo   TEXT COLLATE "C",                                         -- taxonomia (NULL se elegivel)
    justificativa      TEXT COLLATE "C",                                         -- ate 20 palavras
    termo_gerador      TEXT COLLATE "C",                                         -- um dos termos da consulta (conferido pelo codigo)
    sinal_negativo     TEXT COLLATE "C",                                         -- trecho literal do titulo/resumo (conferido pelo codigo)
    dominio_tematico   TEXT COLLATE "C",
    escopo_geografico  TEXT COLLATE "C",                                         -- brasil | internacional | indeterminado
    tipo_documento     TEXT COLLATE "C",
    valido             BIGINT NOT NULL DEFAULT 1,                   -- 0 = alguma conferencia falhou
    problemas          TEXT COLLATE "C",                                         -- JSON: o que falhou
    prompt_versao      TEXT COLLATE "C",
    criado_em          TEXT COLLATE "C" NOT NULL,
    UNIQUE (run_id, fonte, item_id, uf)
);

CREATE TABLE IF NOT EXISTS leitura_referencias (
    artigo_id      BIGINT PRIMARY KEY REFERENCES artigos(artigo_id),
    categoria      TEXT COLLATE "C",
    eixo           TEXT COLLATE "C",
    prioridade     TEXT COLLATE "C",
    status_leitura TEXT COLLATE "C" NOT NULL DEFAULT 'Nao iniciado',
    notas          TEXT COLLATE "C",
    atualizado_em  TEXT COLLATE "C"
);

CREATE TABLE IF NOT EXISTS sugestoes (
    sugestao_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alvo_tipo     TEXT COLLATE "C" NOT NULL CHECK (alvo_tipo IN ('achado', 'artigo')),
    alvo_id       BIGINT NOT NULL,
    valor         TEXT COLLATE "C" NOT NULL,
    motivo        TEXT COLLATE "C" NOT NULL DEFAULT '',
    autor         TEXT COLLATE "C" NOT NULL,
    autor_chave   TEXT COLLATE "C" NOT NULL,                  -- nome do autor normalizado (NFC + casefold), para comparar pessoas
    estado_alvo   TEXT COLLATE "C" NOT NULL,                  -- ficha da decisao que o autor viu (hash de todos os campos da decisao)
    valor_alvo    TEXT COLLATE "C" NOT NULL,                  -- valor da decisao que o autor viu (status_final / decisao)
    criado_em     TEXT COLLATE "C" NOT NULL,
    situacao      TEXT COLLATE "C" NOT NULL DEFAULT 'aberta' CHECK (situacao IN ('aberta', 'aceita', 'descartada')),
    resolvido_por TEXT COLLATE "C",
    resolvido_em  TEXT COLLATE "C"
);

CREATE TABLE IF NOT EXISTS grupos (
    grupo_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT COLLATE "C" NOT NULL UNIQUE,
    fixo BIGINT NOT NULL DEFAULT 0,
    criado_em TEXT COLLATE "C" NOT NULL
);

CREATE TABLE IF NOT EXISTS grupo_permissoes (
    grupo_id BIGINT NOT NULL REFERENCES grupos(grupo_id),
    permissao TEXT COLLATE "C" NOT NULL,
    PRIMARY KEY (grupo_id, permissao)
);

CREATE TABLE IF NOT EXISTS usuarios (
    usuario_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login TEXT COLLATE "C" NOT NULL UNIQUE,
    nome TEXT COLLATE "C" NOT NULL,
    grupo_id BIGINT NOT NULL REFERENCES grupos(grupo_id),
    senha_hash TEXT COLLATE "C" NOT NULL,
    ativo BIGINT NOT NULL DEFAULT 1,
    criado_em TEXT COLLATE "C" NOT NULL,
    ultimo_acesso TEXT COLLATE "C",
    falhas_login BIGINT NOT NULL DEFAULT 0,
    bloqueado_ate TEXT COLLATE "C"
);

CREATE TABLE IF NOT EXISTS sessoes (
    token_hash TEXT COLLATE "C" PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(usuario_id),
    criada_em TEXT COLLATE "C" NOT NULL,
    ultimo_uso TEXT COLLATE "C" NOT NULL
);

CREATE TABLE IF NOT EXISTS auditoria_admin (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quando TEXT COLLATE "C" NOT NULL,
    admin_login TEXT COLLATE "C" NOT NULL,
    acao TEXT COLLATE "C" NOT NULL,
    alvo TEXT COLLATE "C",
    detalhe TEXT COLLATE "C"
);

CREATE TABLE IF NOT EXISTS configuracoes (
    chave TEXT COLLATE "C" PRIMARY KEY,
    valor TEXT COLLATE "C" NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_chamadas_idem
    ON chamadas(run_id, chave_idempotencia) WHERE sucesso = 1;

CREATE INDEX IF NOT EXISTS ix_chamadas_provedor_custo ON chamadas(provedor, custo_usd);

CREATE INDEX IF NOT EXISTS ix_chamadas_run_etapa_chave ON chamadas(run_id, etapa, chave_idempotencia);

CREATE INDEX IF NOT EXISTS ix_achados_classificacao ON achados(classificacao_id);

CREATE INDEX IF NOT EXISTS ix_resultados_web_url_uf ON resultados_web(url_id, uf, resultado_id);

CREATE INDEX IF NOT EXISTS ix_paginas_url_run ON paginas(url_id, run_id);

CREATE INDEX IF NOT EXISTS ix_triagem_escopo_item ON triagem_escopo(fonte, item_id, uf);

CREATE INDEX IF NOT EXISTS ix_sugestoes_alvo ON sugestoes(alvo_tipo, alvo_id, situacao);

CREATE UNIQUE INDEX IF NOT EXISTS ux_sugestoes_aberta ON sugestoes(alvo_tipo, alvo_id, autor_chave, valor, estado_alvo) WHERE situacao = 'aberta';

CREATE UNIQUE INDEX IF NOT EXISTS usuarios_nome_unico ON usuarios (lower(nome));

CREATE INDEX IF NOT EXISTS sessoes_por_usuario ON sessoes (usuario_id);
