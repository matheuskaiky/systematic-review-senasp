-- Busca de literatura cientifica e cinzenta na web (D103 a D106): referencias por URL normalizada e cada resultado,
-- com o conjunto e a consulta que o trouxe.

CREATE TABLE IF NOT EXISTS referencias_web (
    referencia_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url_normalizada  TEXT COLLATE "C" NOT NULL UNIQUE,
    url_original     TEXT COLLATE "C" NOT NULL,
    dominio          TEXT COLLATE "C" NOT NULL,
    primeira_vez_run TEXT COLLATE "C" NOT NULL,
    primeira_vez_em  TEXT COLLATE "C" NOT NULL
);

CREATE TABLE IF NOT EXISTS ocorrencias_web (
    ocorrencia_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chamada_id    BIGINT NOT NULL REFERENCES chamadas(chamada_id),
    run_id        TEXT COLLATE "C" NOT NULL,
    conjunto      TEXT COLLATE "C" NOT NULL,
    consulta_id   TEXT COLLATE "C" NOT NULL,
    referencia_id BIGINT NOT NULL REFERENCES referencias_web(referencia_id),
    posicao       BIGINT,
    titulo        TEXT COLLATE "C",
    snippet       TEXT COLLATE "C",
    data_pub      TEXT COLLATE "C"
);

CREATE INDEX IF NOT EXISTS ix_ocorrencias_web_run ON ocorrencias_web(run_id);
CREATE INDEX IF NOT EXISTS ix_ocorrencias_web_referencia ON ocorrencias_web(referencia_id);
