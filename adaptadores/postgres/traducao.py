def traduz_ddl(sql):
    """CREATE TABLE / CREATE INDEX do SQLite -> PostgreSQL (tipos, identidade, IF NOT EXISTS). Texto compara byte a byte
    (COLLATE "C"), como no SQLite. Chave primaria que e chave estrangeira (1:1) nao vira identidade."""
    s = re.sub(r"\bINTEGER PRIMARY KEY(?= REFERENCES)", "BIGINT PRIMARY KEY", sql)
    s = re.sub(r"\bINTEGER PRIMARY KEY( AUTOINCREMENT)?\b", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", s)
    s = re.sub(r"\bTEXT\b", 'TEXT COLLATE "C"', s)
    s = re.sub(r"\bINTEGER\b", "BIGINT", s)
    s = re.sub(r"\bREAL\b", "DOUBLE PRECISION", s)
    for de in ("CREATE TABLE ", "CREATE INDEX ", "CREATE UNIQUE INDEX "):
        s = s.replace(de, de + "IF NOT EXISTS ").replace("IF NOT EXISTS IF NOT EXISTS", "IF NOT EXISTS")
    return s


def _min_max_escalares(sql):
    """MIN(a, b) / MAX(a, b) com dois argumentos no nivel de cima -> LEAST / GREATEST (agregados ficam como estao)."""
    out, pos, padrao = "", 0, re.compile(r"\b(MIN|MAX)\(")
    while True:
        m = padrao.search(sql, pos)
        if not m:
            return out + sql[pos:]
        prof, j, virgula = 1, m.end(), False
        while prof:
            c = sql[j]
            prof += (c == "(") - (c == ")")
            virgula = virgula or (c == "," and prof == 1)
            j += 1
        out += sql[pos:m.start()] + (("LEAST" if m.group(1) == "MIN" else "GREATEST") if virgula else m.group(1)) + "("
        pos = m.end()


def _fora_de_aspas(sql, funcao):
    """Aplica `funcao` so ao texto fora de literais '...' (strings SQL ficam intactas)."""
    partes = re.split(r"('(?:[^']|'')*')", sql)
    return "".join(p if i % 2 else funcao(p) for i, p in enumerate(partes))


def _decimais_como_real(trecho):
    """Literal decimal (100.0) e numeric no PostgreSQL e real no SQLite: vira double precision."""
    return re.sub(r"(?<![\w.])(\d+\.\d+)(?![\w.])", r"\1::double precision", trecho)


def ordem_dos_nulos(sql):
    """No SQLite o NULL e o menor valor: ORDER BY x poe NULL primeiro, ORDER BY x DESC poe por ultimo. O PostgreSQL faz o
    contrario; cada item de ORDER BY recebe NULLS FIRST / NULLS LAST explicito."""
    out, pos, padrao = "", 0, re.compile(r"\bORDER BY\b")
    while True:
        m = padrao.search(sql, pos)
        if not m:
            return out + sql[pos:]
        out += sql[pos:m.end()]
        j, prof, ini, itens = m.end(), 0, m.end(), []
        while j < len(sql):
            c = sql[j]
            if c == "(":
                prof += 1
            elif c == ")":
                if prof == 0:
                    break
                prof -= 1
            elif prof == 0 and (c in ";" or re.match(r"\s+(LIMIT|OFFSET|ROWS|RANGE|UNION)\b", sql[j:])):
                break
            if prof == 0 and c == ",":
                itens.append(sql[ini:j])
                ini = j + 1
            j += 1
        itens.append(sql[ini:j])
        novos = []
        for it in itens:
            nucleo = it.rstrip()
            fim = it[len(nucleo):]
            if re.search(r"\bNULLS (FIRST|LAST)\s*$", nucleo):
                novos.append(it)
            elif re.search(r"\bDESC\s*$", nucleo):
                novos.append(nucleo + " NULLS LAST" + fim)
            else:
                novos.append(nucleo + " NULLS FIRST" + fim)
        out += ",".join(novos)
        pos = j


def _completar_group_by(sql, coluna):
    pos = sql.find(coluna)
    g = sql.find("GROUP BY", pos)
    m = re.compile(r"\s*(ORDER BY|HAVING|LIMIT|\)|;|\n)").search(sql, g + len("GROUP BY"))
    return sql[:m.start()] + ", " + coluna + sql[m.start():]


def blocos_de_views(texto_schema):
    """[(nome, texto)] de cada `DROP VIEW IF EXISTS x; CREATE VIEW x AS ...;` do schema.sql, na ordem do arquivo."""
    marcas = [m.start() for m in re.finditer(r"^DROP VIEW IF EXISTS [a-z_0-9]+;", texto_schema, re.M)]
    saida = []
    for ini, fim in zip(marcas, marcas[1:] + [len(texto_schema)]):
        trecho = texto_schema[ini:fim]
        corte = re.search(r"^(?:CREATE TABLE|CREATE INDEX|CREATE UNIQUE INDEX)", trecho, re.M)
        trecho = trecho[:corte.start()] if corte else trecho
        ultimo = max(i for i, ch in enumerate(trecho) if ch == ";" and (i + 1 == len(trecho) or trecho[i + 1] in "\n\r "))
        saida.append((re.search(r"CREATE VIEW ([a-z_0-9]+)", trecho).group(1), trecho[:ultimo + 1]))
    return saida


def _ordem_por_dependencia(blocos):
    nomes = [n for n, _ in blocos]
    deps = {n: {o for o in nomes if o != n and re.search(rf"\b{o}\b", t.split(" AS", 1)[1])} for n, t in blocos}
    feitos, ordem = set(), []
    while len(ordem) < len(blocos):
        for n, t in blocos:
            if n not in feitos and deps[n] <= feitos:
                feitos.add(n)
                ordem.append((n, t))
                break
        else:
            raise ValueError("dependencia circular entre views")
    return ordem


def views_postgres(texto_schema):
    """Texto da migracao repetivel R_views.sql a partir do schema.sql."""
    out = []
    for nome, b in _ordem_por_dependencia(blocos_de_views(texto_schema)):
        b = b.replace(f"DROP VIEW IF EXISTS {nome};", f"DROP VIEW IF EXISTS {nome} CASCADE;")
        b = _min_max_escalares(b)
        b = re.sub(r"\be\.rowid\b", "e.ordem_gravacao", b)
        b = re.sub(r"(?<![.\w])rowid\b", "ordem_gravacao", b)
        if nome == "v_termos":
            b = re.sub(r"json_extract\(j\.value, '\$\.([a-z_]+)'\)", r"(j.value ->> '\1')", b)
        for de, para in TROCAS.get(nome, ()):
            assert de in b, (nome, de)
            b = b.replace(de, para)
        for coluna in GROUP_BY_EXTRA.get(nome, ()):
            b = _completar_group_by(b, coluna)
        b = _fora_de_aspas(b, _decimais_como_real)
        b = _fora_de_aspas(b, lambda t: re.sub(r"\bsubstr\(", "compat_substr(", t))
        b = ordem_dos_nulos(b)
        out.append(b)
    return ("-- Views do relatorio e do painel (migracao repetivel): o texto do schema.sql traduzido por\n"
            "-- adaptadores/postgres/traducao.py. NAO edite a mao: rode python scripts/gerar_esquema_postgres.py.\n\n"
            + "\n\n".join(out) + "\n")
