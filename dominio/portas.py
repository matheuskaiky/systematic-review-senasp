from typing import Protocol, Optional
from dominio.modelos import *   # noqa: F401,F403


class BuscaWeb(Protocol):
    nome: str
    def buscar(self, consulta: ConsultaWeb, filtros: FiltrosBusca) -> RespostaBusca: ...


class BuscaAcademica(Protocol):
    nome: str
    def buscar_pagina(self, termo: Termo, inicio: int, filtros: FiltrosAcademicos) -> PaginaAcademica: ...
    def saldo(self) -> Optional[int]: ...      # optional: remaining credits


class Fetcher(Protocol):
    nome: str
    def baixar(self, url: str) -> ArquivoBaixado: ...


class Extrator(Protocol):
    def extrair(self, conteudo: bytes, content_type: str, url: str) -> TextoExtraido: ...


class Classificador(Protocol):
    nome: str          # e.g. "gemini:model-x" (goes into the idempotency key)
    def classificar(self, entrada: EntradaClassificacao, instrucoes: Instrucoes) -> ResultadoClassificacao: ...


class TriadorEscopo(Protocol):
    nome: str          # e.g. "gemini:model-x" (goes into the idempotency key)
    def triar(self, itens: list, instrucoes: Instrucoes) -> ResultadoTriagemLote: ...


class ArmazenamentoBruto(Protocol):
    def salvar(self, categoria: str, run_id: str, chave: str, dados: bytes, ext: str) -> tuple: ...  # (relative_path, sha256)
    def ler(self, caminho: str) -> bytes: ...


class Exportador(Protocol):
    def exportar(self, tabelas: dict, caminho) -> str: ...


class Repositorio(Protocol):
    # run
    def iniciar_execucao(self, comando, config_hash, config_json, commit_git, retomar=None, run_origem=None, ambiente_json=None) -> str: ...
    def obter_run_origem(self, run_id: str) -> Optional[str]: ...    # C5: run_origem guardado (--de); varias separadas por virgula
    def validar_runs_origem(self, runs) -> None: ...                 # encerra se alguma execucao de --de nao existir
    def finalizar_execucao(self, run_id: str, status: str) -> None: ...
    def registrar_saldo(self, run_id, provedor, momento, valor) -> None: ...
    def registrar_metrica(self, run_id, chave, valor) -> None: ...
    def definir_no_relatorio(self, run_id, no_relatorio, motivo=None) -> None: ...   # fora das views agregadas
    def confirmar(self) -> None: ...
    # calls
    def ja_feito(self, run_id: str, chave: str) -> bool: ...
    def resultado_chamada(self, run_id: str, chave: str) -> Optional[tuple]: ...    # C8: (sucesso, n_retornados)
    def contar_falhas(self, run_id: str, chave: str) -> int: ...
    def salvar_chamada(self, **campos) -> int: ...
    def atualizar_chamada(self, chamada_id: int, **campos) -> None: ...
    # academic
    def salvar_artigos(self, chamada_id, run_id, termo_id, artigos) -> int: ...
    # web
    def salvar_resultados_web(self, chamada_id, run_id, consulta, resultados) -> int: ...
    def candidatos_download(self, run_origens) -> list: ...       # uma ou varias execucoes (texto ou lista), sem repeticao
    def urls_com_pagina_ok(self, excluir_run=None) -> set: ...    # url_id com texto extraido em qualquer execucao
    def ultimas_tentativas_download(self, excluir_run=None) -> dict: ...   # {url_id: (resultado, motivo)} da mais recente
    def classificados_validos(self, prompt_versao, classificador, excluir_run=None) -> set: ...   # {(url_id, uf)}
    def salvar_selecao(self, run_id: str, linhas: list) -> None: ...
    def urls_selecionadas(self, run_id: str) -> list: ...
    def salvar_pagina(self, run_id, url_id, chamada_id, arquivo, texto, texto_path) -> int: ...
    def itens_para_classificar(self, run_origens) -> list: ...      # uma ou varias execucoes de download
    def salvar_achados_descartados(self, classificacao_id, descartados) -> None: ...   # fora do vocabulario controlado
    def salvar_classificacao(self, chamada_id, run_id, item, entrada, classificador, prompt_versao, resultado, achados, n_invalidos) -> int: ...
    # triagem de escopo por LLM (opiniao registrada a parte: nunca altera `triagem` nem `achados`)
    def itens_para_triagem_escopo(self, fonte: str) -> list: ...
    def salvar_triagem_escopo(self, run_id, chamada_id, prompt_versao, linhas) -> int: ...
    def triagem_escopo_ja_feita(self, run_id, fonte, item_id, uf="") -> bool: ...
    def triagem_escopo_feita_por_versao(self, fonte: str, prompt_versao: str) -> set: ...   # {(item_id, uf)}
    def triagem_escopo_respondida(self, fonte: str) -> set: ...   # {(item_id, uf)}, qualquer versao do prompt
    def custo_execucao(self, run_id: str) -> float: ...
    # export and imports
    def tabelas_para_exportacao(self) -> dict: ...
    def importar_buscas_manuais(self, df) -> int: ...
    def importar_triagem(self, df, so_historico=False) -> int: ...
    def importar_artigos_manuais(self, df) -> tuple: ...      # (ocorrencias novas, artigos novos)
    def importar_verificacao_achados(self, df, status_permitidos) -> int: ...
    def achados_para_rotulagem(self) -> list: ...                      # achados vigentes (colunas da aba Achados) + fonte_oficial_efetiva
    def artigos_para_rotulagem(self) -> list: ...                      # artigos de r_artigos + veredito do modelo + decisao humana
    def linhas_catalogo(self) -> list[dict]: ...
    def salvar_leitura(self, linhas: list[dict]) -> int: ...
    def candidatos_auditoria_negativos(self) -> list: ...              # paginas sem achado ainda nao conferidas
    def resumo_auditoria_negativos(self) -> dict: ...                  # {n_auditadas, n_perdidas, n_universo}
    # revisao humana, uma decisao por vez (painel)
    def verificar_achado(self, achado_id, status_final, revisor, observacao=None, status_permitidos=None, versao=None) -> None: ...
    def desfazer_ultima_decisao(self, achado_id) -> None: ...
    def desverificar_achado(self, achado_id, revisor, motivo, versao=None) -> None: ...
    def registrar_triagem(self, artigo_id, decisao, revisor, motivo=None, confirmado_em_base=None, link_confirmado=None, etapa="titulo_resumo", versao=None) -> None: ...
    def criar_sugestao(self, alvo_tipo: str, alvo_id: int, valor: str, motivo: str, autor: str, estado: str) -> int: ...   # sugestao aberta (D78)
    def aceitar_sugestao(self, sugestao_id: int, resolvedor: str, status_permitidos: set) -> None: ...   # vira decisao de quem aceita
    def descartar_sugestao(self, sugestao_id: int, resolvedor: str) -> None: ...   # a decisao nao muda
    def copia_de_seguranca(self, pasta, manter: int = 10, sufixo: str = "painel") -> str: ...
    def reclassificar_bloqueios_robots(self, aplicar: bool = False, pasta_backup=None) -> dict: ...
    def fechar(self) -> None: ...


class LeituraPainel(Protocol):
    """Leituras do painel (somente leitura). Devolvem dicionarios e listas simples, nunca cursores nem DataFrames."""
    def resumo_geral(self) -> dict: ...
    def funil(self) -> dict: ...
    def sugestoes_abertas(self, alvo_tipo: str, alvo_id: int) -> list: ...   # sugestoes abertas do item, em ordem
    def sugestao(self, sugestao_id: int) -> Optional[dict]: ...   # uma sugestao ou None
    def estado_decisao(self, alvo_tipo: str, alvo_id: int) -> Optional[str]: ...   # ficha da decisao de hoje (D78)
    def contagem_revisao(self) -> dict: ...
    def execucoes_recentes(self, n: int = 5) -> list: ...
    def resumo_ufs(self) -> list: ...
    def cidades(self) -> list: ...
    def literatura(self) -> dict: ...
    def artigos(self, filtros: dict, pagina: int = 1, por_pagina: int = 50) -> dict: ...
    def ids_fila_triagem(self, filtros: dict) -> list: ...
    def artigo(self, artigo_id: int) -> Optional[dict]: ...
    def contagem_triagem(self) -> dict: ...
    def prisma(self) -> dict: ...
    def execucoes(self) -> list: ...
    def execucao(self, run_id: str) -> Optional[dict]: ...
    def opcoes_chamadas(self) -> dict: ...
    def chamadas(self, filtros: dict, pagina: int = 1, por_pagina: int = 50) -> dict: ...
    def chamada(self, chamada_id: int) -> Optional[dict]: ...
    def achados(self, filtros: dict, pagina: int = 1, por_pagina: int = 50) -> dict: ...
    def ids_fila_revisao(self, filtros: dict) -> list: ...
    def achado(self, achado_id: int) -> Optional[dict]: ...
    def historico_achado(self, achado_id: int) -> list: ...
    def tem_decisao_para_desfazer(self, achado_id: int) -> bool: ...
    def titulos_artigos(self, ids: list) -> dict:
        """Titulo de cada artigo da lista (janela da fila lateral)."""
        ...
    def resumo_achados(self, ids: list) -> dict:
        """Tecnologia, UF e cidade de cada achado da lista (janela da fila lateral)."""
        ...
    def atividade_por_revisor(self) -> list[dict]: ...
