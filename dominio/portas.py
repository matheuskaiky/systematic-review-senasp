from typing import Protocol, Optional
from dominio.modelos import *   # noqa: F401,F403


class BuscaWeb(Protocol):
    nome: str
    def buscar(self, consulta: ConsultaWeb, filtros: FiltrosBusca) -> RespostaBusca: ...


class BuscaAcademica(Protocol):
    nome: str
    def buscar_pagina(self, termo: Termo, inicio: int, filtros: FiltrosAcademicos) -> PaginaAcademica: ...
    def saldo(self) -> Optional[int]: ...      # optional: remaining credits


class Fetcher(Protocol):
    nome: str
    def baixar(self, url: str) -> ArquivoBaixado: ...


class Extrator(Protocol):
    def extrair(self, conteudo: bytes, content_type: str, url: str) -> TextoExtraido: ...


class Classificador(Protocol):
    nome: str          # e.g. "gemini:model-x" (goes into the idempotency key)
    def classificar(self, entrada: EntradaClassificacao, instrucoes: Instrucoes) -> ResultadoClassificacao: ...


class ArmazenamentoBruto(Protocol):
    def salvar(self, categoria: str, run_id: str, chave: str, dados: bytes, ext: str) -> tuple: ...  # (relative_path, sha256)
    def ler(self, caminho: str) -> bytes: ...


class Exportador(Protocol):
    def exportar(self, tabelas: dict, caminho) -> str: ...


class Repositorio(Protocol):
    # run
    def iniciar_execucao(self, comando, config_hash, config_json, commit_git, retomar=None) -> str: ...
    def finalizar_execucao(self, run_id: str, status: str) -> None: ...
    def registrar_saldo(self, run_id, provedor, momento, valor) -> None: ...
    def registrar_metrica(self, run_id, chave, valor) -> None: ...
    def confirmar(self) -> None: ...
    # calls
    def ja_feito(self, run_id: str, chave: str) -> bool: ...
    def salvar_chamada(self, **campos) -> int: ...
    def atualizar_chamada(self, chamada_id: int, **campos) -> None: ...
    # academic
    def salvar_artigos(self, chamada_id, run_id, termo_id, artigos) -> int: ...
    # web
    def salvar_resultados_web(self, chamada_id, run_id, consulta, resultados) -> int: ...
    def candidatos_download(self, run_origem: str) -> list: ...
    def salvar_selecao(self, run_id: str, linhas: list) -> None: ...
    def urls_selecionadas(self, run_id: str) -> list: ...
    def salvar_pagina(self, run_id, url_id, chamada_id, arquivo, texto, texto_path) -> int: ...
    def itens_para_classificar(self, run_origem: str) -> list: ...
    def salvar_classificacao(self, chamada_id, run_id, item, entrada, classificador, prompt_versao, resultado, achados, n_invalidos) -> int: ...
    # export and imports
    def tabelas_para_exportacao(self) -> dict: ...
    def importar_buscas_manuais(self, df) -> int: ...
    def importar_triagem(self, df) -> int: ...
    def importar_verificacao_achados(self, df, status_permitidos) -> int: ...
