"""Gera as migracoes PostgreSQL a partir do esquema SQLite (D96, ADR-postgresql-neon).

    python scripts/gerar_esquema_postgres.py            # regrava R_views.sql (views derivadas do schema.sql)
    python scripts/gerar_esquema_postgres.py --tabelas  # escreve a migracao inicial de tabelas, se ainda nao existir

As tabelas saem de um banco SQLite vazio criado pelo proprio codigo (com as colunas de _COLUNAS_NOVAS) e do banco de
contas. Migracao versionada ja aplicada nunca e regravada: mudanca de tabela vira um arquivo V novo, escrito a mao."""
import sqlite3
import sys
import tempfile
from pathlib import Path

RAIZ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(RAIZ))

from adaptadores.contas_sqlite import ContasSQLite  # noqa: E402
from adaptadores.postgres.traducao import traduz_ddl, views_postgres  # noqa: E402
from adaptadores.repositorio_sqlite import RepositorioSQLite  # noqa: E402

PASTA = RAIZ / "adaptadores" / "postgres" / "migracoes"
TABELAS = PASTA / "V0002_tabelas.sql"


def _ddl(caminho, excluir=()):
    con = sqlite3.connect(caminho)
    try:
        tab = [s for n, s in con.execute("SELECT name, sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' "
                                         "AND sql IS NOT NULL ORDER BY rowid") if n not in excluir]
        idx = [r[0] for r in con.execute("SELECT sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL ORDER BY rowid")]
        return tab, idx
    finally:
        con.close()


def tabelas_postgres():
    with tempfile.TemporaryDirectory() as d:
        RepositorioSQLite(Path(d) / "pesquisa.db").fechar()
        ContasSQLite(Path(d) / "contas.db").garantir_padrao()
        tp, ip = _ddl(Path(d) / "pesquisa.db", excluir=("meta_schema",))
        tc, ic = _ddl(Path(d) / "contas.db")
    partes = ["-- Tabelas e indices da pesquisa e das contas (gerado do esquema SQLite real por scripts/gerar_esquema_postgres.py)."]
    for s in tp + tc:
        s = traduz_ddl(s)
        if s.startswith("CREATE TABLE IF NOT EXISTS execucoes ("):
            s = s.rstrip().rstrip(")").rstrip() + (",\n    ordem_gravacao BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE"
                                                  "  -- desempate pela ordem de gravacao (o rowid do SQLite)\n)")
        partes.append(s + ";")
    partes += [traduz_ddl(s) + ";" for s in ip + ic]
    return "\n\n".join(partes) + "\n"


if __name__ == "__main__":
    PASTA.mkdir(parents=True, exist_ok=True)
    if "--tabelas" in sys.argv:
        if TABELAS.exists():
            sys.exit(f"{TABELAS.name} ja existe e e versionada: mudanca de tabela vira um arquivo V novo.")
        TABELAS.write_text(tabelas_postgres(), encoding="utf-8")
        print("escrito", TABELAS.name)
    (PASTA / "R_views.sql").write_text(views_postgres((RAIZ / "adaptadores" / "schema.sql").read_text(encoding="utf-8")),
                                       encoding="utf-8")
    print("escrito R_views.sql")
