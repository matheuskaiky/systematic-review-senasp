def test_maiusculas_so_ascii_como_no_sqlite(banco):
    """lower/upper e LIKE do SQLite so mudam letras ASCII: 'É' e 'é' sao diferentes; 'A' e 'a' sao iguais."""
    pool, chaves, _ = banco
    c = X.ConexaoPostgres(pool, chaves)
    lite = sqlite3.connect(":memory:")
    try:
        consultas = [("SELECT lower(?) AS r", ("ÉDSON",)), ("SELECT upper(?) AS r", ("édson",)),
                     ("SELECT CASE WHEN ? LIKE ? THEN 1 ELSE 0 END AS r", ("É", "é")),
                     ("SELECT CASE WHEN ? LIKE ? THEN 1 ELSE 0 END AS r", ("ABC", "a%")),
                     ("SELECT CASE WHEN lower(?) = lower(?) THEN 1 ELSE 0 END AS r", ("Édson", "ÉDSON"))]
        for sql, p in consultas:
            assert c.execute(sql, p).fetchone()["r"] == lite.execute(sql, p).fetchone()[0], sql
    finally:
        c.close()
        lite.close()


