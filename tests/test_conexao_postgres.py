def test_conexao_derrubada_volta_ao_pool_e_vira_erro_do_sqlite(banco):
    _, chaves, url = banco
    pool = X.criar_pool(url, maximo=1)
    try:
        c = X.ConexaoPostgres(pool, chaves)
        c.execute("INSERT INTO t (nome) VALUES (?)", ("a",))
        pid = c._conn.info.backend_pid
        with psycopg.connect(url, autocommit=True) as adm:
            adm.execute("SELECT pg_terminate_backend(%s)", (pid,))
        with pytest.raises(sqlite3.OperationalError) as e:
            c.execute("INSERT INTO t (nome) VALUES (?)", ("b",))
        assert str(e.value) == "banco PostgreSQL indisponível"
        c.rollback()                                               # nunca levanta com a conexao caida
        c.close()
        outra = X.ConexaoPostgres(pool, chaves)                    # o unico lugar do pool foi devolvido
        try:
            assert outra.execute("SELECT COUNT(*) AS n FROM t").fetchone()["n"] == 0
        finally:
            outra.close()
    finally:
        pool.close()


