def test_comando_que_falha_nao_desfaz_o_resto_da_transacao(banco):
    pool, chaves, url = banco
    c = X.ConexaoPostgres(pool, chaves)
    try:
        c.execute("INSERT INTO t (nome) VALUES (?)", ("a",))
        with pytest.raises(sqlite3.IntegrityError):
            c.execute("INSERT INTO t (nome) VALUES (?)", ("a",))           # repetido
        with pytest.raises(sqlite3.IntegrityError):
            c.execute("INSERT INTO t (nome) VALUES (?)", (None,))          # NOT NULL
        with pytest.raises(sqlite3.OperationalError):
            c.execute("SELECT coluna_que_nao_existe FROM t")               # leitura que falha dentro da transacao
        c.execute("INSERT INTO t (nome) VALUES (?)", ("b",))
        c.commit()
        assert _nomes(url) == ["a", "b"]
    finally:
        c.close()


