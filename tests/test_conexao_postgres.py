def _nomes(url):
    with psycopg.connect(url) as c:
        return [r[0] for r in c.execute("SELECT nome FROM t ORDER BY id")]


def test_leitura_nao_abre_transacao_e_gravacao_abre(banco):
    pool, chaves, url = banco
    c = X.ConexaoPostgres(pool, chaves)
    try:
        assert c.execute("SELECT 1 AS um").fetchone()["um"] == 1
        assert c.in_transaction is False
        cur = c.execute("INSERT INTO t (nome) VALUES (?)", ("a",))
        assert c.in_transaction is True and cur.lastrowid == 1 and cur.rowcount == 1
        assert _nomes(url) == []                                  # ainda nao confirmado
        c.commit()
        assert c.in_transaction is False and _nomes(url) == ["a"]
    finally:
        c.close()


def test_begin_immediate_depois_de_leitura_pega_a_trava(banco):
    """O padrao dos repositorios: `if not in_transaction: BEGIN IMMEDIATE` depois de ler. O segundo gravador espera."""
    pool, chaves, _ = banco
    a, b = X.ConexaoPostgres(pool, chaves), X.ConexaoPostgres(pool, chaves)
    tempos = {}

    def segundo():
        b.execute("SELECT 1")
        if not b.in_transaction:
            b.execute("BEGIN IMMEDIATE")
        tempos["b"] = time.monotonic()
        b.rollback()
    try:
        a.execute("SELECT 1")
        if not a.in_transaction:
            a.execute("BEGIN IMMEDIATE")
        inicio = time.monotonic()
        f = threading.Thread(target=segundo)
        f.start()
        time.sleep(0.6)
        a.commit()
        f.join(10)
        assert tempos["b"] - inicio >= 0.5
    finally:
        a.close()
        b.close()


