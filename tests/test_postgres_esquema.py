@pytest.mark.postgres
def test_tabelas_e_colunas_iguais_as_do_sqlite(pg_url, tmp_path):
    import psycopg
    from adaptadores.contas_sqlite import ContasSQLite
    from adaptadores.repositorio_sqlite import RepositorioSQLite
    M.aplicar(pg_url)
    RepositorioSQLite(tmp_path / "p.db").fechar()
    ContasSQLite(tmp_path / "c.db").garantir_padrao()
    esperado = {}
    for banco in ("p.db", "c.db"):
        con = sqlite3.connect(tmp_path / banco)
        for (t,) in con.execute("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' AND name <> 'meta_schema'"):
            esperado[t] = [r[1] for r in con.execute(f"PRAGMA table_info({t})")]
    esperado["execucoes"] = esperado["execucoes"] + ["ordem_gravacao"]
    esperado["versao_esquema"] = ["arquivo", "sha256", "aplicada_em"]
    with psycopg.connect(pg_url) as c:
        obtido = {}
        for t, col in c.execute("SELECT table_name, column_name FROM information_schema.columns WHERE table_schema = 'public' "
                                "AND table_name IN (SELECT table_name FROM information_schema.tables WHERE table_schema = 'public' "
                                "AND table_type = 'BASE TABLE') ORDER BY table_name, ordinal_position"):
            obtido.setdefault(t, []).append(col)
    assert obtido == esperado


