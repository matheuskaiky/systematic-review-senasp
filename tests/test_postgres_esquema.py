@pytest.mark.postgres
def test_texto_compara_byte_a_byte_como_no_sqlite(pg_url):
    import psycopg
    M.aplicar(pg_url)
    nomes = ["b", "B", "a", "Á", "á", "Z", "ana", "Ana"]
    s = sqlite3.connect(":memory:")
    s.execute("CREATE TABLE t (nome TEXT)")
    s.executemany("INSERT INTO t VALUES (?)", [(n,) for n in nomes])
    with psycopg.connect(pg_url) as c:
        c.execute(T.traduz_ddl("CREATE TEMP TABLE t (nome TEXT)"))           # o mesmo tratamento das tabelas do esquema
        for n in nomes:
            c.execute("INSERT INTO t VALUES (%s)", (n,))
        pg = [r[0] for r in c.execute("SELECT nome FROM t ORDER BY nome")]
        assert c.execute("SELECT 'b' < 'B'::text COLLATE \"C\"").fetchone()[0] is False
    assert pg == [r[0] for r in s.execute("SELECT nome FROM t ORDER BY nome")]


