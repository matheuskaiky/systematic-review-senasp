@pytest.mark.postgres
def test_duas_aplicacoes_ao_mesmo_tempo_aplicam_cada_arquivo_uma_vez(pg_url):
    resultados, erros = [], []

    def roda():
        try:
            resultados.append(M.aplicar(pg_url))
        except Exception as e:          # noqa: BLE001
            erros.append(e)
    fios = [threading.Thread(target=roda) for _ in range(3)]
    for f in fios:
        f.start()
    for f in fios:
        f.join()
    assert erros == [] and sorted(sum(resultados, [])) == sorted(ARQUIVOS)


@pytest.mark.postgres
@pytest.mark.parametrize("expr,valores", [
    ("SUM(v = 1)", [1, 0, None, 1]), ("SUM(v = 1)", [None, None]), ("SUM(v = 1)", []), ("SUM(v IS NULL)", [None, 1]),
    ("MAX(v = 1)", [0, 1]), ("MAX(v = 1)", [0, 0]), ("MAX(v = 1)", [None]), ("MIN(v = 1)", [1, 0]), ("MIN(v = 1)", [1, 1]),
    ("instr(group_concat(CAST(v AS TEXT), ';'), '1')", [0, 1, None]), ("group_concat(CAST(v AS TEXT))", [2, None, 3]),
])
def test_agregados_de_compatibilidade_iguais_ao_sqlite(pg_url, expr, valores):
    import psycopg
    M.aplicar(pg_url)
    s = sqlite3.connect(":memory:")
    s.execute("CREATE TABLE t (v INTEGER)")
    s.executemany("INSERT INTO t VALUES (?)", [(v,) for v in valores])
    with psycopg.connect(pg_url) as c:
        c.execute("CREATE TEMP TABLE t (v BIGINT)")
        for v in valores:
            c.execute("INSERT INTO t VALUES (%s)", (v,))
        assert c.execute(f"SELECT {expr} FROM t").fetchone()[0] == s.execute(f"SELECT {expr} FROM t").fetchone()[0]


@pytest.mark.postgres
def test_round_igual_ao_do_sqlite(pg_url):
    import random
    import psycopg
    M.aplicar(pg_url)
    random.seed(20261020)
    casos = [(2.675, 2), (1.005, 2), (0.045, 2), (-0.045, 2), (0.125, 2), (2.5, 0), (-2.5, 0), (0.49999999999999994, 0),
             (1e-7, 3), (123456.785, 2), (4503599627370497.0, 2), (0.0, 2), (12.3, -1), (1.23456789, 40)]
    casos += [(100.0 * random.randint(0, 500) / random.randint(1, 700), random.randint(0, 3)) for _ in range(1500)]
    casos += [(random.randint(-99999, 99999) / 10 ** random.randint(1, 6), random.randint(0, 5)) for _ in range(1500)]
    s = sqlite3.connect(":memory:")
    with psycopg.connect(pg_url) as c:
        dif = [(x, n) for x, n in casos
               if c.execute("SELECT round(%s::float8, %s)", (x, n)).fetchone()[0] != s.execute("SELECT round(?, ?)", (x, n)).fetchone()[0]]
    assert dif == []


@pytest.mark.postgres
def test_json_extract_igual_ao_do_sqlite(pg_url):
    import psycopg
    M.aplicar(pg_url)
    doc = '{"q": "reconhecimento \\"facial\\"", "num": 20, "a": {"b": "x"}, "nulo": null}'
    s = sqlite3.connect(":memory:")
    with psycopg.connect(pg_url) as c:
        for caminho in ("$.q", "$.num", "$.a.b", "$.nulo", "$.falta"):
            pg = c.execute("SELECT json_extract(%s, %s)", (doc, caminho)).fetchone()[0]
            sq = s.execute("SELECT json_extract(?, ?)", (doc, caminho)).fetchone()[0]
            assert pg == (None if sq is None else str(sq)), caminho


